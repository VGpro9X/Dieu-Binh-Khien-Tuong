function createUnit(
  id: string,
  classId: UnitClassId,
  team: TeamId,
  x: number,
  y: number,
): CombatUnitState {
  const definition = UNIT_DEFINITIONS[classId];
  return {
    ...definition,
    id,
    team,
    position: { x, y },
    hp: definition.maxHp,
    hasMoved: false,
    hasActed: false,
  };
}

